#!/usr/bin/env python3
"""Writes scripts/ort-slim/ops.config from the ONNX graphs the app runs through its own ONNX Runtime.

  gen_ops_config.py <out ops.config> <model.onnx> [<model.onnx> ...]

Run it with the same onnxruntime version the slim build uses (scripts/ort-slim/build.sh does, on the build machine). The result is
the union, over every model, of
  1. the operators in the graph as shipped (including subgraphs), and
  2. the operators in the graph after ORT's own optimiser at every level (basic, extended, all - the app opens its sessions
     at ALL_OPT, with the CPU layout transform), because the optimiser fuses nodes into com.microsoft ops (NhwcFusedConv,
     MatMulNBits, FusedMatMul, ...) whose kernels must exist, and
  3. EXTRA below: operators the optimiser creates on the way and drops again. They do not show in any output graph, but
     with no CPU kernel for them the node gets no execution provider and session creation fails (Gemm, from MatMul+Add), plus the Arm-only fusions the x86 box cannot show.
The final proof is always the phone: open every model with the slim build (scripts/ort-slim/phone_ab.sh does).
"""
import os
import sys
import tempfile
from collections import defaultdict

import onnx
import onnxruntime as ort

# domain -> ops that intermediate passes make; added under the model's opset of that domain (ai.onnx) or version 1.
EXTRA = {
    "ai.onnx": ["Gemm", "MatMul", "Add", "Transpose", "Reshape", "Cast", "Squeeze", "Unsqueeze"],
    # What the Arm optimiser makes from the patch-embedding Conv (the build machine is x86: it makes NCHWc ops there instead).
    "com.microsoft": ["FusedConv", "NhwcFusedConv"],
}
# x86-only kernels (the box that generates the file is x86; the app is arm64-v8a only): never needed on the phone.
X86_ONLY = ("com.microsoft.nchwc",)


def graph_ops(graph, acc):
    for n in graph.node:
        acc.add((n.domain or "ai.onnx", n.op_type))
        for a in n.attribute:
            if a.type == onnx.AttributeProto.GRAPH:
                graph_ops(a.g, acc)
            elif a.type == onnx.AttributeProto.GRAPHS:
                for g in a.graphs:
                    graph_ops(g, acc)


def model_ops(path):
    m = onnx.load(path, load_external_data=False)
    acc = set()
    graph_ops(m.graph, acc)
    for f in m.functions:
        for n in f.node:
            acc.add((n.domain or "ai.onnx", n.op_type))
    opsets = {(o.domain or "ai.onnx"): o.version for o in m.opset_import}
    return acc, opsets


def optimised_ops(path):
    acc = set()
    levels = [
        ort.GraphOptimizationLevel.ORT_ENABLE_BASIC,
        ort.GraphOptimizationLevel.ORT_ENABLE_EXTENDED,
        ort.GraphOptimizationLevel.ORT_ENABLE_ALL,
    ]
    for level in levels:
        with tempfile.TemporaryDirectory() as d:
            out = os.path.join(d, "opt.onnx")
            so = ort.SessionOptions()
            so.graph_optimization_level = level
            so.optimized_model_filepath = out
            so.intra_op_num_threads = 1
            ort.InferenceSession(path, so, providers=["CPUExecutionProvider"])
            ops, _ = model_ops(out)
            acc |= ops
    return acc


def main():
    out, models = sys.argv[1], sys.argv[2:]
    if not models:
        sys.exit(__doc__)
    want = defaultdict(set)  # (domain, opset) -> ops
    for path in models:
        src, opsets = model_ops(path)
        opt = optimised_ops(path)
        for domain, op in src | opt:
            if domain in X86_ONLY:
                continue
            opset = opsets.get(domain, 1)
            want[(domain, opset)].add(op)
        for domain, ops in EXTRA.items():
            for op in ops:
                want[(domain, opsets.get(domain, 1))].add(op)
        print(f"{os.path.basename(os.path.dirname(path))}/{os.path.basename(path)}: "
              f"{len(src)} source ops, {len(opt - src)} more after optimising: "
              f"{sorted(f'{d}:{o}' for d, o in opt - src)}", file=sys.stderr)
    with open(out, "w") as f:
        f.write("# Generated by scripts/ort-slim/gen_ops_config.py from:\n")
        for p in models:
            f.write(f"#   {os.path.basename(os.path.dirname(p))}/{os.path.basename(p)}\n")
        for (domain, opset) in sorted(want):
            f.write(f"{domain};{opset};{','.join(sorted(want[(domain, opset)]))}\n")
    print(open(out).read())


main()
